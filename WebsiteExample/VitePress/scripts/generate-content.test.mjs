import assert from 'node:assert/strict'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { execFileSync } from 'node:child_process'
import { test } from 'node:test'

test('content generation handles escaped pipes, mixed-case fields, and obsolete pages', () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), '88k-content-test-'))
  const write = (relative, content) => {
    const target = path.join(root, relative)
    fs.mkdirSync(path.dirname(target), { recursive: true })
    fs.writeFileSync(target, content)
  }
  const read = relative => fs.readFileSync(path.join(root, relative), 'utf8')
  const exists = relative => fs.existsSync(path.join(root, relative))
  try {
    write('VitePress/scripts/generate-content.mjs', fs.readFileSync(new URL('./generate-content.mjs', import.meta.url)))
    write('VitePress/deployment.mjs', fs.readFileSync(new URL('../deployment.mjs', import.meta.url)))
    let deploymentMode = 'custom'
    write('VitePress/src/.vitepress/config.js', 'const navItems = [\n]\nexport default {\n  title: "Site",\n  base: "/site/"\n}\n')
    write('Contents/site.md', '---\nsite_title: Test\n---\n| 名称 | 路径 |\n| --- | --- |\n| A\\|B | /Scores/ |\n')
    write('Contents/index.md', '# Home\n')
    write('Contents/footer.md', '© Test\n\nLicense notice\n')
    write('Contents/Sections/Scores.md', '# Scores\n')
    const score = '---\ntitle: Example\nViDeO: BV1234567890\nillusts: Placeholder\npdf: /example.pdf\nPdf_Title: Preview\n---\n| Key | Value |\n| --- | --- |\n| A\\|B | C\\|D |\n'
    write('Contents/Scores/example.md', score)
    write('Contents/Scores/Song_Name-[Full] (Live)_Hard.md', score)
    write('Contents/Scores/Marked (＊) （＊）_Hard.md', score)
    write('Contents/Scores/Infinite Strife,_Beyond.md', score)
    write('VitePress/src/old/nested/stale.md', '# Old\n')
    write('VitePress/src/Scores/EXAMPLE.md', '# Previous filename casing\n')
    write('VitePress/src/public/keep.md', 'Asset')
    write('VitePress/src/.vitepress/keep.md', 'Config')
    const run = () => execFileSync(process.execPath, [path.join(root, 'VitePress/scripts/generate-content.mjs')], { stdio: 'pipe', env: { ...process.env, SITE_DEPLOY_MODE: deploymentMode } })
    run()
    assert.ok(fs.readdirSync(path.join(root, 'VitePress/src/Scores')).includes('example.md'))
    assert.ok(!fs.readdirSync(path.join(root, 'VitePress/src/Scores')).includes('EXAMPLE.md'))
    assert.ok(exists('VitePress/src/Scores/Song_Name-［Full］ (Live)_Hard.md'))
    assert.ok(exists('VitePress/src/Scores/Marked_Hard.md'))
    const sidebar = JSON.parse(read('VitePress/src/.vitepress/score-sidebar.json'))
    const commaRecord = sidebar.find(record => record.link.includes('Strife'))
    assert.equal(commaRecord.link, '/Scores/Infinite%20Strife,_Beyond')
    assert.equal(decodeURI(commaRecord.link).slice(1), 'Scores/Infinite Strife,_Beyond')
    assert.ok(sidebar.some(record => record.link === '/Scores/Song_Name-%EF%BC%BBFull%EF%BC%BD%20%28Live%29_Hard'))
    assert.deepEqual(JSON.parse(read('VitePress/src/.vitepress/footer.json')), ['© Test', 'License notice'])
    assert.equal(exists('VitePress/src/footer.md'), false)
    const page = read('VitePress/src/Scores/example.md')
    assert.match(page, /high_quality=1&danmaku=1/)
    assert.ok(page.indexOf('class="video-layout-row"') < page.indexOf('<ScoreSection title="【版面1】"'))
    assert.match(page, /<ScoreSection title="【版面1】" sectionId="score-basic-information">[\s\S]*?<ScoreTables[\s\S]*?<\/ScoreSection>/)
    assert.match(page, /<ScoreSection title="【版面2】" sectionId="score-preview">[\s\S]*?<PdfViewer[\s\S]*?<\/ScoreSection>/)
    assert.match(page, /<PdfViewer src="\/example.pdf" title="Preview"/)
    const groups = JSON.parse(decodeURIComponent(page.match(/<ScoreTables groups="([^"]+)"/)[1]))
    assert.deepEqual(groups[0].tables[0].cells, [['Key', 'Value'], ['A|B', 'C|D']])
    assert.match(read('VitePress/src/.vitepress/config.js'), /text: 'A\|B'/)
    assert.equal(exists('VitePress/src/old/nested/stale.md'), false)
    assert.equal(read('VitePress/src/public/keep.md'), 'Asset')
    assert.equal(read('VitePress/src/.vitepress/keep.md'), 'Config')
    fs.renameSync(path.join(root, 'Contents/Scores/example.md'), path.join(root, 'Contents/Scores/renamed.md'))
    run()
    assert.equal(exists('VitePress/src/Scores/example.md'), false)
    assert.equal(exists('VitePress/src/Scores/renamed.md'), true)
    fs.unlinkSync(path.join(root, 'Contents/Scores/renamed.md'))
    run()
    assert.equal(exists('VitePress/src/Scores/renamed.md'), false)
    assert.match(read('VitePress/src/Scores/index.md'), /section-index-marker/)
    assert.equal(exists('VitePress/src/Sections/Scores.md'), false)
    write('Contents/Scores/parts.md', score.replace('BV1234567890', 'BV1234567890?p=2'))
    run()
    assert.match(read('VitePress/src/Scores/parts.md'), /bvid=BV1234567890&page=2&/)
    write('Contents/Scores/parts.md', score.replace('BV1234567890', 'https://www.bilibili.com/video/BV1234567890/?p=3'))
    run()
    assert.match(read('VitePress/src/Scores/parts.md'), /bvid=BV1234567890&page=3&/)
    write('Contents/Scores/parts.md', score.replace('BV1234567890', 'BV1234567890?p=0'))
    run()
    assert.match(read('VitePress/src/Scores/parts.md'), /<ScoreVideo src=""/)
    for (const videoSource of [score.replace('BV1234567890', ''), score.replace('BV1234567890', 'invalid'), score.replace('BV1234567890', 'BV123456'), score.replace(/^ViDeO:.*\n/m, '')]) {
      write('Contents/Scores/parts.md', videoSource)
      run()
      assert.match(read('VitePress/src/Scores/parts.md'), /<ScoreVideo src=""/)
    }
    fs.unlinkSync(path.join(root, 'Contents/Scores/parts.md'))
    write('VitePress/src/Scores/classified.md', '# Legacy flattened page\n')
    write('Contents/Scores/YY/classified.md', score)
    write('Contents/Scores/POP/classified.md', score)
    run()
    assert.equal(exists('VitePress/src/Scores/classified.md'), false)
    assert.equal(exists('VitePress/src/Scores/YY/classified.md'), true)
    assert.equal(exists('VitePress/src/Scores/POP/classified.md'), true)
    const categorized = JSON.parse(read('VitePress/src/.vitepress/score-sidebar.json'))
    assert.equal(categorized.find(record => record.link === '/Scores/YY/classified').category, 'game')
    assert.equal(categorized.find(record => record.link === '/Scores/POP/classified').category, 'pop')
    fs.renameSync(path.join(root, 'Contents/Scores/YY/classified.md'), path.join(root, 'Contents/Scores/POP/moved.md'))
    run()
    assert.equal(exists('VitePress/src/Scores/classified.md'), false)
    assert.equal(exists('VitePress/src/Scores/POP/moved.md'), true)
    assert.equal(exists('VitePress/src/Scores/YY/classified.md'), false)
    const migrated = JSON.parse(read('VitePress/src/.vitepress/score-sidebar.json'))
    assert.equal(migrated.some(record => record.link === '/Scores/YY/classified'), false)
    assert.equal(migrated.find(record => record.link === '/Scores/POP/moved').category, 'pop')
    for (const [speed, expected] of [['~116', 116], ['76~100', 100], ['100~76', 100], ['76～100.5', 100.5]]) {
      write('Contents/Scores/bpmrange.md', score + `| 参数6 [BPM] | ♩= ${speed} |\n`)
      run()
      const metadata = JSON.parse(read('VitePress/src/.vitepress/score-sidebar.json'))
      assert.equal(metadata.find(record => record.link === '/Scores/bpmrange').bpm, expected)
    }
    // Root deployment and subpath deployment must resolve the same public image.
    write('VitePress/src/public/images/cover.svg', '<svg xmlns="http://www.w3.org/2000/svg"/>')
    for (const [mode, base] of [['custom', '/'], ['github', '/website-example/']]) {
      deploymentMode = mode
      write('VitePress/src/.vitepress/config.js', 'const navItems = [\n]\nexport default {\n  title: "Site",\n  base: "' + base + '"\n}\n')
      for (const image of ['/images/cover.svg', base + 'images/cover.svg']) {
        write('Contents/Scores/image.md', score.replace('illusts: Placeholder', 'illusts: ' + image))
        run()
        assert.ok(read('VitePress/src/Scores/image.md').includes('<ScoreImage src="/images/cover.svg"'))
      }
    }
    write('Contents/Scores/visibility.md', score)
    run()
    assert.equal(exists('VitePress/src/Scores/visibility.md'), true)
    write('Contents/Scores/visibility.md', score.replace('---\n', '---\nvisible: false\n'))
    run()
    assert.equal(exists('VitePress/src/Scores/visibility.md'), true)
    assert.equal(JSON.parse(read('VitePress/src/.vitepress/score-sidebar.json')).find(record => record.link === '/Scores/visibility').visible, false)
    write('Contents/Scores/visibility.md', score.replace('---\n', '---\nVISIBLE: true\n'))
    run()
    assert.equal(exists('VitePress/src/Scores/visibility.md'), true)
    write('Contents/Scores/visibility.md', score.replace('---\n', '---\nVISIBLE: typo\n'))
    assert.throws(run, /VISIBLE 必须为 true 或 false/)
    fs.unlinkSync(path.join(root, 'Contents/Scores/visibility.md'))
    write('VitePress/src/public/illusts/YY/Variant_0_HD.svg', '<svg/>')
    for (const marker of [' （＊）', '（*）', ' (*)']) {
      write('Contents/Scores/variant.md', score.replace('illusts: Placeholder', 'illusts: /illusts/YY/Variant' + marker + '_0_HD.svg'))
      run()
      assert.match(read('VitePress/src/Scores/variant.md'), /<ScoreImage src="\/illusts\/YY\/Variant_0_HD.svg"/)
    }
    write('Contents/Scores/unpublished.md', score.replace('pdf: /example.pdf', 'pdf: '))
    run()
    assert.match(read('VitePress/src/Scores/unpublished.md'), /<PdfViewer src=""/)
    write('Contents/Scores/index.md', '# Conflicting source\n')
    assert.throws(run, /页面输出路径冲突/)
  } finally {
    // Only remove the unique fixture directory allocated above.
    assert.equal(path.dirname(root), os.tmpdir())
    assert.ok(path.basename(root).startsWith('88k-content-test-'))
    fs.rmSync(root, { recursive: true, force: true })
  }
})
